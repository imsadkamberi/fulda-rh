/* Renderimi automatik i Footer-it */
function renderFooter() {
  if (document.querySelector('footer')) return;
  const footerHTML = `
  <footer>
    <p data-i="f.copy">© 2026 Fulda RH – Të gjitha të drejtat e rezervuara.</p>
  </footer>
  `;
  document.body.insertAdjacentHTML('beforeend', footerHTML);
}

function renderIcons() {
  document.querySelectorAll('.ico[data-ic]').forEach(el => {
    const key = el.getAttribute('data-ic');
    if (icons[key]) el.innerHTML = icons[key];
  });
}

function toggleMenu() {
  const nav = document.getElementById('nav');
  if (nav) nav.classList.toggle('open');
}

function toggleTheme() {
  const current = document.documentElement.getAttribute('data-theme') || 'dark';
  const next = current === 'dark' ? 'light' : 'dark';
  document.documentElement.setAttribute('data-theme', next);
  localStorage.setItem('pref_theme', next);
  updateThemeBtn(next);
}

function updateThemeBtn(theme) {
  const btn = document.getElementById('theme-btn');
  if (btn) btn.textContent = theme === 'dark' ? '☀️' : '🌙';
}

function applyLang(lang) {
  document.querySelectorAll('[data-i]').forEach(el => {
    const key = el.getAttribute('data-i');
    if (dict[lang] && dict[lang][key]) {
      el.textContent = dict[lang][key];
    }
  });
  localStorage.setItem('pref_lang', lang);
}

function setLang(lang) {
  applyLang(lang);
  ['sq', 'mk', 'en'].forEach(l => {
    const btn = document.getElementById(`btn-${l}`);
    if (btn) btn.classList.toggle('on', l === lang);
  });
}

/* Ekzekutimi i sigurt në çdo faqe */
function initApp() {
  renderHeader();
  renderFooter();
  renderIcons();

  const savedTheme = localStorage.getItem('pref_theme') || 'dark';
  document.documentElement.setAttribute('data-theme', savedTheme);
  updateThemeBtn(savedTheme);

  const savedLang = localStorage.getItem('pref_lang') || 'sq';
  setLang(savedLang);
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initApp);
} else {
  initApp();
}
